#!/usr/bin/env bash
# Embed the folder models' pinned file tables (scripts/whisperkit_files.tsv,
# scripts/parakeet_files.tsv) into the app, so Settings' in-app download
# fetches and checks exactly what `make whisperkit-model` / `make
# parakeet-model` do. The TSVs stay the one source of truth; this writes a
# verbatim copy as Swift string literals (no SwiftPM resource bundle to
# package). FolderModelPinsTests fails until it's re-run after a TSV change.
#
# Usage: bash scripts/embed_folder_model_pins.sh
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$HERE/../Sources/VoiceType/Transcription/FolderModelPins+Tables.swift"

table() {   # <swift name> <tsv>
  printf '    static let %s = #"""\n' "$1"
  cat "$HERE/$2"
  printf '\n"""#\n'
}

{
  echo "// Generated by scripts/embed_folder_model_pins.sh from scripts/*_files.tsv. Don't edit: re-run it."
  echo ""
  echo "extension FolderModelPins {"
  table whisperKitTable whisperkit_files.tsv
  echo ""
  table parakeetTable parakeet_files.tsv
  echo "}"
} >"$OUT"
echo "Wrote $OUT" >&2
